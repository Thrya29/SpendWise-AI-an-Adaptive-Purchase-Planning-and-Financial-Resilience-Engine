"""Migrations must build exactly the schema the models describe, and be reversible."""

import os
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from app.core.config import get_settings

BACKEND = Path(__file__).resolve().parents[2]


@pytest.fixture
def alembic_cfg(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Config:
    url = os.environ.get("SPENDWISE_MIGRATION_TEST_URL") or (
        f"sqlite+aiosqlite:///{(tmp_path / 'migrations.db').as_posix()}"
    )
    monkeypatch.setenv("SPENDWISE_DATABASE_URL", url)
    get_settings.cache_clear()
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND / "alembic"))
    yield cfg
    get_settings.cache_clear()


def test_upgrade_matches_models_and_downgrade_is_clean(alembic_cfg: Config) -> None:
    command.upgrade(alembic_cfg, "head")
    try:
        command.check(alembic_cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"Models and migrations have drifted: {exc}")
    command.downgrade(alembic_cfg, "base")
    command.upgrade(alembic_cfg, "head")

"""How planner solve time grows with the number of items and the horizon.

The CP-SAT model has one variable per item and period, and one constraint per record-low day
per scenario, so cost grows with items x periods x scenarios. This measures it on one
household with three protected scenarios, from a typical wish list to the API's limit
(300 items, 24 months).

Run:  python -m research.planner_scaling [--repeats N] [--out PATH]
"""

from __future__ import annotations

import argparse
import platform
import random
import statistics
import sys
import time
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.domain.cashflow import (  # noqa: E402
    IncomeShock,
    IncomeSpec,
    ObligationSpec,
    ReservePolicy,
    Scenario,
)
from app.domain.money import Money  # noqa: E402
from app.domain.planner import NamedScenario, PlanItem, plan_purchases  # noqa: E402
from app.domain.recurrence import Frequency  # noqa: E402

TODAY = date(2026, 11, 3)
ITEMS = (5, 25, 50, 100, 200, 300)
HORIZONS = (6, 12, 24)
SALARY = 150_000_00


def inr(minor: int) -> Money:
    return Money(minor, "INR")


def wish_list(n: int, horizon: int, rng: random.Random) -> list[PlanItem]:
    items = []
    for i in range(n):
        tier = rng.choice(("need", "want", "want", "desire"))
        target = (
            TODAY + timedelta(days=rng.randint(5, 30 * horizon)) if rng.random() < 0.7 else None
        )
        items.append(
            PlanItem(
                ref=f"i{i}",
                name=f"item {i}",
                tier=tier,
                priority=rng.randint(1, 5),
                unit_price=round(SALARY * rng.uniform(0.02, 0.6)),
                quantity=1,
                deadline=rng.choice(("hard", "soft", "none")) if target else "none",
                target_date=target,
                group=f"g{i // 3}" if i % 7 == 0 else None,
            )
        )
    return items


def solve(n: int, horizon: int, seed: int) -> tuple[float, str, int]:
    rng = random.Random(seed)
    started = time.perf_counter()
    result = plan_purchases(
        opening_balance=inr(300_000_00),
        today=TODAY,
        horizon_months=horizon,
        items=wish_list(n, horizon, rng),
        incomes=[IncomeSpec("Salary", inr(SALARY), Frequency.MONTHLY, date(2026, 11, 1))],
        obligations=[
            ObligationSpec("Rent", inr(45_000_00), Frequency.MONTHLY, date(2026, 11, 5)),
            ObligationSpec("Bills", inr(20_000_00), Frequency.MONTHLY, date(2026, 11, 12)),
            ObligationSpec("Groceries", inr(4_000_00), Frequency.WEEKLY, date(2026, 11, 7)),
        ],
        scenarios=[
            NamedScenario("As expected", Scenario()),
            NamedScenario("Salary delayed 1 month", Scenario(IncomeShock(1, TODAY))),
            NamedScenario("Salary delayed 2 months", Scenario(IncomeShock(2, TODAY))),
        ],
        reserve=ReservePolicy(2),
    )
    elapsed = (time.perf_counter() - started) * 1000
    bought = sum(d.pay_on is not None for d in result.decisions)
    return elapsed, result.solver_status, bought


def run(repeats: int) -> list[dict[str, object]]:
    rows = []
    for horizon in HORIZONS:
        for n in ITEMS:
            runs = [solve(n, horizon, seed) for seed in range(repeats)]
            times = [r[0] for r in runs]
            rows.append({
                "items": n, "horizon": horizon,
                "median_ms": statistics.median(times), "max_ms": max(times),
                "optimal": sum(r[1] == "optimal" for r in runs), "runs": repeats,
                "bought": statistics.median(r[2] for r in runs),
            })  # fmt: skip
    return rows


def report(rows: list[dict[str, object]], repeats: int) -> str:
    lines = [
        "# Planner scaling",
        "",
        f"Generated by `python -m research.planner_scaling --repeats {repeats}` on "
        f"{platform.processor() or platform.machine()} ({platform.system()}), Python "
        f"{platform.python_version()}, one CP-SAT worker, 5 s time limit.",
        "Three protected scenarios (as expected, salary 1 and 2 months late), weekly and monthly",
        "bills, a mix of tiers, deadlines and alternatives groups. Times include building the",
        "cash-flow ledgers, the model, solving and explaining every decision.",
        "",
        "| Horizon | Items | Median | Slowest | Proven optimal | Items scheduled (median) |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['horizon']} months | {r['items']} | {r['median_ms']:.0f} ms | "
            f"{r['max_ms']:.0f} ms | {r['optimal']}/{r['runs']} | {r['bought']:.0f} |"
        )
    lines += [
        "",
        "When the 5 s limit is reached, CP-SAT returns the best plan found so far, which still",
        "satisfies every reserve constraint (only optimality is unproven). The API reports this",
        'as "Best found". The planner endpoint is rate-limited to 30 runs per user per minute.',
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument(
        "--out", type=Path, default=ROOT / "docs" / "results" / "planner-scaling.md"
    )
    args = parser.parse_args()
    text = report(run(args.repeats), args.repeats)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(text.encode())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
